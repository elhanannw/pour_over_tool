"""Apply the reviewed, shared security headers to both static hosting configs."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
headers = json.loads((root / 'security/headers.json').read_text(encoding='utf-8'))
vercel_file = root / 'vercel.json'
vercel = json.loads(vercel_file.read_text(encoding='utf-8'))
vercel['headers'] = [entry for entry in vercel['headers'] if entry['source'] != '/(.*)']
vercel['headers'].insert(0, {'source': '/(.*)', 'headers': [{'key': key, 'value': value} for key, value in headers.items()]})
vercel_file.write_text(json.dumps(vercel, indent=2) + '\n', encoding='utf-8')

netlify_file = root / 'netlify.toml'
netlify = netlify_file.read_text(encoding='utf-8').split('# Shared security headers')[0].rstrip()
netlify += '\n\n# Shared security headers — generated by scripts/sync-security.py\n[[headers]]\n  for = "/*"\n  [headers.values]\n'
netlify += ''.join(f'    {key} = {json.dumps(value)}\n' for key, value in headers.items())
netlify_file.write_text(netlify, encoding='utf-8')
print('Synchronized security headers for Vercel and Netlify.')
